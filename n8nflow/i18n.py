def get_lang() -> str:
    try:
        import streamlit as st

        if "lang" in st.session_state:
            return st.session_state.lang
    except Exception:
        pass
    return "fa"


def set_lang(lang: str) -> None:
    try:
        import streamlit as st

        st.session_state.lang = "en" if lang == "en" else "fa"
    except Exception:
        pass


def t(key: str, **kwargs) -> str:
    lang = get_lang()
    table = TRANSLATIONS.get(lang) or TRANSLATIONS["fa"]
    text = table.get(key) or TRANSLATIONS["en"].get(key) or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except Exception:
            pass
    return text


def is_rtl() -> bool:
    return get_lang() == "fa"
